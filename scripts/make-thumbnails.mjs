/**
 * Writes a small companion image for every background, and regenerates the
 * asset module that maps an id to its require().
 *
 * The picker draws every visible card through Skia. A background is 1290x2796,
 * which is about 13.8 MB once decoded, so a grid of them would hold hundreds of
 * megabytes and crash a mid-range phone. These thumbnails are large enough to
 * cover a card at 3x and cost about 0.4 MB decoded.
 *
 * Run after adding or retiring a background:
 *   node scripts/make-thumbnails.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(
  fileURLToPath(new URL('../package.json', import.meta.url)),
);
const sourceDirectory = join(root, 'assets/images/backgrounds');
const thumbDirectory = join(sourceDirectory, 'thumbs');
const assetModule = join(
  root,
  'src/features/wallpaper/backgroundThumbAssets.ts',
);

/** Covers a 110pt card at 3x with room to spare, keeping the source aspect. */
const THUMB_WIDTH = 360;
const QUALITY = 72;

function backgroundIds() {
  return readdirSync(sourceDirectory)
    .filter((name) => name.endsWith('.webp'))
    .map((name) => name.slice(0, -'.webp'.length))
    .sort();
}

function writeThumbnail(id) {
  execFileSync('cwebp', [
    '-quiet',
    '-q',
    String(QUALITY),
    '-resize',
    String(THUMB_WIDTH),
    '0',
    join(sourceDirectory, `${id}.webp`),
    '-o',
    join(thumbDirectory, `${id}.webp`),
  ]);
}

function writeAssetModule(ids) {
  const entries = ids
    .map(
      (id) =>
        `  '${id}': require('../../../assets/images/backgrounds/thumbs/${id}.webp'),`,
    )
    .join('\n');
  writeFileSync(
    assetModule,
    `/**
 * Generated by scripts/make-thumbnails.mjs. Do not edit by hand.
 *
 * Metro needs a literal require() per asset, so the picker cannot build these
 * paths at runtime.
 */
export const backgroundThumbAssets: Readonly<Record<string, number>> = {
${entries}
};
`,
  );
}

const ids = backgroundIds();
mkdirSync(thumbDirectory, { recursive: true });
for (const id of ids) {
  writeThumbnail(id);
}
writeAssetModule(ids);
console.log(`make-thumbnails: wrote ${ids.length} thumbnails.`);
